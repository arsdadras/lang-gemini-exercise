"""Create or complete the role worktrees: one worktree, branch, and `.venv` per role (ADR-0019).

    python scripts/setup_worktrees.py [--roles lead,mentor] [--no-sync] [--no-push]
                                      [--copy-runtime]

Idempotent: an existing worktree is only checked and completed. For each role it
  - adds `../lce-<role>` on branch `<role>` (from `origin/<role>` if it exists, else from
    `origin/main`),
  - records the role in the worktree's own git config (`agentlab.role`),
  - writes `CLAUDE.local.md` (never committed) so every session there loads the role's charter,
  - copies `.env` from the main checkout when the worktree has none (its content is never shown),
  - runs `uv sync` when the worktree has no `.venv`,
  - pushes the branch when `origin` doesn't have it.
`--copy-runtime` also copies the main checkout's `out/state/` and `.chroma_index/` into a
worktree that has none (the mentor's move-in; run it while no app is running).
"""

from __future__ import annotations

import argparse
import shutil
import subprocess
import sys
from pathlib import Path

from workspace import (
    MAIN_BRANCH,
    REMOTE,
    ROLE_CONFIG_KEY,
    ROLES,
    ROOT,
    git,
    main_checkout,
)

CLAUDE_LOCAL = """\
# CLAUDE.local.md

Generated by `scripts/setup_worktrees.py`; not committed. This worktree is the **{role}**
office's workspace, on branch `{role}`: every session here plays the {role} role (`CLAUDE.md`,
"Session roles"). Start from the session hook's summary, and end with `/handoff`.

@offices/{role}/README.md
"""

RUNTIME_DIRS = ("out/state", ".chroma_index")


def registered_worktrees(main: Path) -> set[Path]:
    listing = git("worktree", "list", "--porcelain", cwd=main)
    return {
        Path(line.split(" ", 1)[1]).resolve()
        for line in listing.splitlines()
        if line.startswith("worktree ")
    }


def has_ref(main: Path, ref: str) -> bool:
    return bool(git("rev-parse", "--verify", "--quiet", ref, cwd=main, check=False))


def add_worktree(main: Path, role: str, path: Path) -> str:
    if path.resolve() in registered_worktrees(main):
        return "worktree present"
    if path.exists():
        raise SystemExit(f"{path} exists but is not a worktree of this repository")
    if has_ref(main, f"refs/heads/{role}"):
        git("worktree", "add", str(path), role, cwd=main)
        return f"worktree added on the existing branch {role}"
    if has_ref(main, f"refs/remotes/{REMOTE}/{role}"):
        git(
            "worktree",
            "add",
            "--track",
            "-b",
            role,
            str(path),
            f"{REMOTE}/{role}",
            cwd=main,
        )
        return f"worktree added, tracking {REMOTE}/{role}"
    start = f"{REMOTE}/{MAIN_BRANCH}"
    git("worktree", "add", "--no-track", "-b", role, str(path), start, cwd=main)
    return f"worktree added on a new branch {role} from {start}"


def set_role(main: Path, role: str, path: Path) -> str:
    git("config", "extensions.worktreeConfig", "true", cwd=main)
    git("config", "--worktree", ROLE_CONFIG_KEY, role, cwd=path)
    return f"{ROLE_CONFIG_KEY}={role}"


def exclude_everywhere(main: Path, pattern: str = "CLAUDE.local.md") -> str:
    """Ignore `pattern` in every worktree through the shared `info/exclude`.

    `.gitignore` lists it too, but a role branch that hasn't merged that `.gitignore` yet would
    otherwise show the file as untracked, and `/handoff` commits everything it sees.
    """
    common = Path(
        git("rev-parse", "--path-format=absolute", "--git-common-dir", cwd=main)
    )
    exclude = common / "info" / "exclude"
    lines = exclude.read_text(encoding="utf-8").splitlines() if exclude.exists() else []
    if pattern in lines:
        return f"{pattern} excluded"
    exclude.parent.mkdir(parents=True, exist_ok=True)
    with exclude.open("a", encoding="utf-8", newline="\n") as handle:
        handle.write(f"{pattern}\n")
    return f"{pattern} added to info/exclude"


def write_claude_local(role: str, path: Path) -> str:
    target = path / "CLAUDE.local.md"
    if target.exists():
        return "CLAUDE.local.md present"
    target.write_text(CLAUDE_LOCAL.format(role=role), encoding="utf-8", newline="\n")
    return "CLAUDE.local.md written"


def copy_env(main: Path, path: Path) -> str:
    source, target = main / ".env", path / ".env"
    if target.exists():
        return ".env present"
    if not source.exists():
        return ".env missing in the main checkout too: create one before live runs"
    shutil.copy2(source, target)
    return ".env copied from the main checkout"


def copy_runtime(main: Path, path: Path) -> list[str]:
    notes = []
    for rel in RUNTIME_DIRS:
        source, target = main / rel, path / rel
        if target.exists():
            notes.append(f"{rel} present")
        elif source.exists():
            shutil.copytree(source, target)
            notes.append(f"{rel} copied")
    return notes


def sync_venv(path: Path) -> str:
    if (path / ".venv").exists():
        return ".venv present"
    result = subprocess.run(
        ["uv", "sync", "--quiet"], cwd=path, capture_output=True, text=True, check=False
    )
    if result.returncode:
        return f"uv sync FAILED: {result.stderr.strip()[-200:]}"
    return ".venv created (uv sync)"


def push_branch(main: Path, role: str, path: Path) -> str:
    if has_ref(main, f"refs/remotes/{REMOTE}/{role}"):
        upstream = git(
            "rev-parse", "--abbrev-ref", f"{role}@{{upstream}}", cwd=path, check=False
        )
        if upstream != f"{REMOTE}/{role}":
            git("branch", f"--set-upstream-to={REMOTE}/{role}", role, cwd=path)
            return f"upstream set to {REMOTE}/{role}"
        return f"{REMOTE}/{role} present"
    git("push", "--quiet", "-u", REMOTE, role, cwd=path)
    return f"pushed {role} to {REMOTE}"


def setup(
    main: Path,
    role: str,
    *,
    sync: bool = True,
    push: bool = True,
    runtime: bool = False,
) -> list[str]:
    path = main.parent / f"lce-{role}"
    notes = [add_worktree(main, role, path), set_role(main, role, path)]
    notes += [
        exclude_everywhere(main),
        write_claude_local(role, path),
        copy_env(main, path),
    ]
    if runtime:
        notes += copy_runtime(main, path)
    if sync:
        notes.append(sync_venv(path))
    if push:
        notes.append(push_branch(main, role, path))
    return [f"{role}: {path}"] + [f"  {note}" for note in notes]


def main(argv: list[str] | None = None) -> int:
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--roles", default=",".join(ROLES))
    parser.add_argument("--no-sync", action="store_true", help="skip uv sync")
    parser.add_argument(
        "--no-push", action="store_true", help="don't push new branches"
    )
    parser.add_argument(
        "--copy-runtime", action="store_true", help="copy out/state, .chroma_index"
    )
    args = parser.parse_args(argv)
    roles = [r.strip() for r in args.roles.split(",") if r.strip()]
    unknown = [r for r in roles if r not in ROLES]
    if unknown:
        print(f"unknown role(s): {', '.join(unknown)}")
        return 2
    main_root = main_checkout(ROOT)
    for role in roles:
        lines = setup(
            main_root,
            role,
            sync=not args.no_sync,
            push=not args.no_push,
            runtime=args.copy_runtime,
        )
        print("\n".join(lines))
    return 0


if __name__ == "__main__":
    sys.exit(main())
